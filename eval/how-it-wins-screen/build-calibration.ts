/*
 * Writes packages/llm/src/how-it-wins-screen-calibration.ts from a whole-corpus screen run:
 *
 *   npx tsx eval/how-it-wins-screen/run.ts --bias 400 --seed hiw-screen-calibration-1 --cap-usd 1.5
 *   npx tsx eval/how-it-wins-screen/build-calibration.ts --run eval/runs/how-it-wins-screen/<stamp>
 *
 * Rerun both whenever HOW_IT_WINS_SCREEN_VERSION, the Jev model, or the rubric changes.
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { HOW_IT_WINS_STRATEGIES } from "@cold-start/core";
import { HOW_IT_WINS_SCREEN_MODEL, HOW_IT_WINS_SCREEN_VERSION } from "@cold-start/llm";

const QUANTILE_POINTS = 20;
const MIN_COMPANIES = 100;

async function main() {
  const index = process.argv.indexOf("--run");
  const runDir = index === -1 ? undefined : process.argv[index + 1];
  if (!runDir) throw new Error("--run <whole-corpus screen run dir> is required");
  const files = (await readdir(runDir)).filter((name) => name.endsWith(".json") && name !== "summary.json");
  const runs = await Promise.all(files.map(async (name) => JSON.parse(await readFile(path.join(runDir, name), "utf8")) as {
    version: string; model: string; strategies: Record<string, { support: number }>;
  }));
  const current = runs.filter((run) => run.version === HOW_IT_WINS_SCREEN_VERSION && run.model === HOW_IT_WINS_SCREEN_MODEL);
  if (current.length < MIN_COMPANIES) {
    throw new Error(`${current.length} companies match ${HOW_IT_WINS_SCREEN_VERSION}/${HOW_IT_WINS_SCREEN_MODEL}; need ${MIN_COMPANIES}`);
  }
  const quantiles: Record<string, number[]> = {};
  for (const strategy of HOW_IT_WINS_STRATEGIES) {
    const values = current.map((run) => run.strategies[strategy.id]!.support).sort((a, b) => a - b);
    quantiles[strategy.id] = Array.from({ length: QUANTILE_POINTS }, (_, i) =>
      Number(values[Math.min(values.length - 1, Math.floor(((i + 1) / QUANTILE_POINTS) * values.length) - 1)]!.toFixed(4)));
  }
  const body = `// Generated by eval/how-it-wins-screen/build-calibration.ts. Do not edit by hand.
// Per-strategy support quantiles across the non-holdout corpus, for the screen version below.
import type { HowItWinsStrategyId } from "@cold-start/core";

export const HOW_IT_WINS_SCREEN_CALIBRATION: {
  version: string;
  model: string;
  companies: number;
  quantiles: Partial<Record<HowItWinsStrategyId, readonly number[]>>;
} = {
  version: ${JSON.stringify(HOW_IT_WINS_SCREEN_VERSION)},
  model: ${JSON.stringify(HOW_IT_WINS_SCREEN_MODEL)},
  companies: ${current.length},
  quantiles: {
${Object.entries(quantiles).map(([id, values]) => `    ${id}: [${values.join(", ")}]`).join(",\n")}
  }
};
`;
  await writeFile(path.resolve("packages/llm/src/how-it-wins-screen-calibration.ts"), body);
  process.stdout.write(`Calibrated ${HOW_IT_WINS_STRATEGIES.length} strategies over ${current.length} companies\n`);
}

main().catch((error) => {
  process.stderr.write(`${(error as Error).stack ?? error}\n`);
  process.exit(1);
});
